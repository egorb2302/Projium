const DICTS = { en, ru }
const KEY = 'tracker-lang'

let lang = /^ru\b/i.test(navigator.language ?? '') ? 'ru' : 'en'
try {
  const saved = localStorage.getItem(KEY)
  if (DICTS[saved]) lang = saved
} catch {}

export const getLang = () => lang
export const setLang = next => {
  lang = DICTS[next] ? next : 'ru'
  try {
    localStorage.setItem(KEY, lang)
  } catch {}
}
export const t = (key, ...args) => {
  const v = DICTS[lang][key] ?? en[key]
  return typeof v === 'function' ? v(...args) : v
}
export const fmtDate = ts => new Date(ts).toLocaleString(t('locale'), { dateStyle: 'medium', timeStyle: 'short' })
